using Microsoft.Xna.Framework;
using Microsoft.Xna.Framework.Graphics;
using Microsoft.Xna.Framework.Input;

namespace Acom.Desktop;

using GameTime = Microsoft.Xna.Framework.GameTime; // Acom.GameTime is the in-game clock

/// <summary>
/// MonoGame host: owns the window and main loop, feeds input into the engine and
/// presents the engine's indexed screen as a GPU texture (nearest-neighbour, letterboxed).
/// </summary>
internal sealed class AcomHost : Microsoft.Xna.Framework.Game
{
	/// <summary>Pixel density of the screen buffer: 4 = HD (1280x800 for the 320x200 layout).</summary>
	private const int RenderScale = 4;

	private readonly GraphicsDeviceManager _graphics;
	private readonly MonoGameAudioDevice _audio = new();
	private SdlInput? _input;
	private readonly HostOptions _options;
	private Acom.Game? _game;
	private Texture2D? _texture;
	private SpriteBatch? _spriteBatch;
	private byte[] _upload = [];
	private long _uploadedFrame = -1;
	private int _frames;

	public AcomHost(HostOptions options, string title)
	{
		_options = options;
		_graphics = new GraphicsDeviceManager(this)
		{
			PreferredBackBufferWidth = Screen.ORIGINAL_WIDTH * RenderScale,
			PreferredBackBufferHeight = Screen.ORIGINAL_HEIGHT * RenderScale,
			SynchronizeWithVerticalRetrace = true,
		};
		IsMouseVisible = false; // the game draws its own cursor (Interface/Cursor); C++ shows an invisible hardware cursor
		IsFixedTimeStep = true;
		TargetElapsedTime = TimeSpan.FromSeconds(1.0 / 60);
		Window.AllowUserResizing = true;
		Window.Title = title;
	}

	protected override void Initialize()
	{
		Surface.DefaultScale = RenderScale;
		var screen = new Screen(Screen.ORIGINAL_WIDTH, Screen.ORIGINAL_HEIGHT, RenderScale);
		if (_options.Demo)
		{
			// The demo loads no options.cfg: start from the defaults of Options::create (audio format, volumes, ...)
			Options.Create();
			Options.ResetDefault(false);
		}
		else
		{
			// Options.Init ran in Program (like C++ main before creating the Game)
			Options.baseXResolution = Options.displayWidth;
			Options.baseYResolution = Options.displayHeight;
			// C++ Screen() opens the window with the configured display mode (resetDisplay -> SDL_SetVideoMode)
			ApplyVideoMode(Options.displayWidth, Options.displayHeight);
		}
		screen.VideoModeHandler = ApplyVideoMode;
		Mixer.Device = _audio; // Game.InitAudio opens it (or runs muted without audio hardware)
		_game = new Acom.Game(screen)
		{
			// SDL_WarpMouse: the engine's window coordinates are the SDL2 client coordinates MonoGame uses,
			// so the position needs no mapping. The resulting motion event is generated by the engine.
			WarpMouseHandler = (x, y) => Mouse.SetPosition(x, y),
		};
		UpdateWindowSize(); // states created below may call Screen.ResetDisplay, which reads the window size
		_game.SetState(_options.Demo ? new DemoState() : new StartState());
		_input = new SdlInput();
		Window.ClientSizeChanged += (_, _) => OnClientSizeChanged();
		base.Initialize();
		UpdateWindowSize();
	}

	protected override void LoadContent()
	{
		var surface = _game!.Screen.Surface;
		_texture = new Texture2D(GraphicsDevice, surface.PhysicalWidth, surface.PhysicalHeight, false, SurfaceFormat.Color);
		_upload = new byte[surface.PhysicalWidth * surface.PhysicalHeight * 4];
		_spriteBatch = new SpriteBatch(GraphicsDevice);
	}

	protected override void UnloadContent()
	{
		// C++ deletes the Game at the end of main (saving the options); headless checks leave the config alone.
		if (!_options.Demo && _options.ScreenshotPath == null)
			_game?.Shutdown();
		Mixer.CloseAudio();
		Mixer.Device = null;
		_audio.Dispose();
		_input?.Dispose();
		_texture?.Dispose();
		_spriteBatch?.Dispose();
	}

	/// <summary>Applies the configured window mode and display size (C++ SDL_SetVideoMode, see <see cref="Screen.VideoModeHandler"/>).</summary>
	private void ApplyVideoMode(int width, int height)
	{
		width = Math.Max(width, Screen.ORIGINAL_WIDTH);
		height = Math.Max(height, Screen.ORIGINAL_HEIGHT);
		if (_graphics.PreferredBackBufferWidth != width || _graphics.PreferredBackBufferHeight != height
			|| _graphics.IsFullScreen != Options.fullscreen || Window.IsBorderless != Options.borderless)
		{
			_graphics.PreferredBackBufferWidth = width;
			_graphics.PreferredBackBufferHeight = height;
			_graphics.IsFullScreen = Options.fullscreen;
			Window.IsBorderless = Options.borderless;
			_graphics.ApplyChanges();
		}
		UpdateWindowSize();
	}

	private void OnClientSizeChanged()
	{
		UpdateWindowSize();
		// Options::allowResize: the game adapts its base resolution to the window (Game: SDL_VIDEORESIZE)
		var bounds = Window.ClientBounds;
		if (_game != null && Options.allowResize && bounds.Width > 0 && bounds.Height > 0
			&& (bounds.Width != Options.displayWidth || bounds.Height != Options.displayHeight))
		{
			_graphics.PreferredBackBufferWidth = bounds.Width;
			_graphics.PreferredBackBufferHeight = bounds.Height;
			_game.PushEvent(new SDL_Event { type = SDLEventType.SDL_VIDEORESIZE, resize = { w = bounds.Width, h = bounds.Height } });
		}
	}

	private void UpdateWindowSize()
	{
		var bounds = Window.ClientBounds;
		if (_game != null && bounds.Width > 0 && bounds.Height > 0)
			_game.Screen.SetWindowSize(bounds.Width, bounds.Height);
	}

	protected override void Update(GameTime gameTime)
	{
		var game = _game!;
		_input!.Flush(game);
		game.Update();
		if (game.IsQuitting)
			Exit();
		base.Update(gameTime);
	}

	protected override void Draw(GameTime gameTime)
	{
		var screen = _game!.Screen;
		_game.Render();
		var surface = screen.Surface;
		if (_texture!.Width != surface.PhysicalWidth || _texture.Height != surface.PhysicalHeight)
		{
			// Screen.ResetDisplay changed the base resolution
			_texture.Dispose();
			_texture = new Texture2D(GraphicsDevice, surface.PhysicalWidth, surface.PhysicalHeight, false, SurfaceFormat.Color);
			_upload = new byte[surface.PhysicalWidth * surface.PhysicalHeight * 4];
			_uploadedFrame = -1;
		}
		if (screen.FrameNumber != _uploadedFrame)
		{
			screen.Frame.CopyTo(_upload);
			_texture!.SetData(_upload);
			_uploadedFrame = screen.FrameNumber;
		}

		GraphicsDevice.Clear(Color.Black);
		var (w, h) = screen.DisplaySize;
		_spriteBatch!.Begin(samplerState: SamplerState.PointClamp);
		_spriteBatch.Draw(_texture, new Rectangle(screen.LeftBlackBand, screen.TopBlackBand, w, h), Color.White);
		_spriteBatch.End();
		base.Draw(gameTime);

		if (_options.ScreenshotPath != null && ++_frames == _options.ScreenshotAfterFrames)
		{
			using (var file = File.Create(_options.ScreenshotPath))
				_texture!.SaveAsPng(file, _texture.Width, _texture.Height);
			Exit();
		}
	}
}

/// <summary>Command line options of the desktop host.</summary>
/// <param name="ScreenshotPath">Save a screenshot here and quit (headless checks).</param>
/// <param name="ScreenshotAfterFrames">Number of frames drawn before the screenshot.</param>
/// <param name="Demo">Show the rendering demo instead of starting the game.</param>
/// <param name="GameArgs">All other arguments, for the game's own command line (<see cref="CrossPlatform.SetArgs"/>).</param>
internal sealed record HostOptions(string? ScreenshotPath, int ScreenshotAfterFrames, bool Demo, IReadOnlyList<string> GameArgs)
{
	/// <summary>
	/// Parses <c>--screenshot &lt;file.png&gt; [--frames &lt;n&gt;]</c> (used for automated checks) and <c>--demo</c>;
	/// everything else is left for the game (e.g. <c>-data &lt;folder&gt;</c>, <c>-oxceFoo true</c>).
	/// </summary>
	public static HostOptions Parse(string[] args)
	{
		string? screenshot = null;
		int frames = 30;
		bool demo = false;
		var rest = new List<string>();
		for (int i = 0; i < args.Length; ++i)
		{
			if (args[i] == "--screenshot" && i + 1 < args.Length)
				screenshot = args[++i];
			else if (args[i] == "--frames" && i + 1 < args.Length)
				frames = int.Parse(args[++i], System.Globalization.CultureInfo.InvariantCulture);
			else if (args[i] == "--demo")
				demo = true;
			else
				rest.Add(args[i]);
		}
		return new HostOptions(screenshot, frames, demo, rest);
	}
}
