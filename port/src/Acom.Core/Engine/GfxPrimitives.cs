	/// <summary>Right edge of the clipping rectangle (clip_rect.x + clip_rect.w - 1 stored in a Sint16).</summary>
	private static short Right(Surface dst) => (short)(dst.Width - 1);

	/// <summary>Bottom edge of the clipping rectangle.</summary>
	private static short Bottom(Surface dst) => (short)(dst.Height - 1);

	/// <summary>Is the clipping rectangle empty?</summary>
	private static bool NoClip(Surface dst) => dst.Width == 0 || dst.Height == 0;

	/// <summary>Pixel draw (pixelColor with alpha 255), clipped.</summary>
	public static void PixelColor(Surface dst, short x, short y, byte color)
	{
		if (x >= 0 && x <= dst.Width - 1 && y >= 0 && y <= dst.Height - 1)
			dst.FillLogical(x, y, 1, 1, color);
	}

	/// <summary>Draws a horizontal line (hlineColor), clipped.</summary>
	public static void HLineColor(Surface dst, short x1, short x2, short y, byte color)
	{
		// Check visibility of clipping rectangle
		if (NoClip(dst))
			return;
		// Swap x1, x2 if required to ensure x1<=x2
		if (x1 > x2)
			(x1, x2) = (x2, x1);
		// Get clipping boundary and check visibility of hline
		short left = 0;
		if (x2 < left)
			return;
		short right = Right(dst);
		if (x1 > right)
			return;
		short top = 0;
		short bottom = Bottom(dst);
		if (y < top || y > bottom)
			return;
		// Clip x
		if (x1 < left)
			x1 = left;
		if (x2 > right)
			x2 = right;
		dst.FillLogical(x1, y, x2 - x1 + 1, 1, color);
	}

	/// <summary>Draws a vertical line (vlineColor), clipped.</summary>
	public static void VLineColor(Surface dst, short x, short y1, short y2, byte color)
	{
		// Check visibility of clipping rectangle
		if (NoClip(dst))
			return;
		// Swap y1, y2 if required to ensure y1<=y2
		if (y1 > y2)
			(y1, y2) = (y2, y1);
		// Get clipping boundary and check visibility of vline
		short left = 0;
		short right = Right(dst);
		if (x < left || x > right)
			return;
		short top = 0;
		if (y2 < top)
			return;
		short bottom = Bottom(dst);
		if (y1 > bottom)
			return;
		// Clip y
		if (y1 < top)
			y1 = top;
		if (y2 > bottom)
			y2 = bottom;
		dst.FillLogical(x, y1, 1, y2 - y1 + 1, color);
	}

	/// <summary>Internal clip-encoding routine: which edges of the rectangle a point lies beyond.</summary>
	private static int ClipEncode(short x, short y, short left, short top, short right, short bottom)
	{
		int code = 0;
		if (x < left)
			code |= CLIP_LEFT_EDGE;
		else if (x > right)
			code |= CLIP_RIGHT_EDGE;
		if (y < top)
			code |= CLIP_TOP_EDGE;
		else if (y > bottom)
			code |= CLIP_BOTTOM_EDGE;
		return code;
	}

	/// <summary>Float to Sint16 like the C cast on x86 (via a 32-bit integer).</summary>
	private static short ToSint16(float f) => unchecked((short)(int)f);

	/// <summary>Clips a line to the clipping rectangle (Cohen-Sutherland with a float slope).</summary>
	/// <returns>True if (a part of) the line is visible.</returns>
	private static bool ClipLine(Surface dst, ref short x1, ref short y1, ref short x2, ref short y2)
	{
		// Get clipping boundary
		short left = 0;
		short right = Right(dst);
		short top = 0;
		short bottom = Bottom(dst);
		while (true)
		{
			int code1 = ClipEncode(x1, y1, left, top, right, bottom);
			int code2 = ClipEncode(x2, y2, left, top, right, bottom);
			if ((code1 | code2) == 0)
				return true;
			if ((code1 & code2) != 0)
				return false;
			if (code1 == 0)
			{
				(x1, x2) = (x2, x1);
				(y1, y2) = (y2, y1);
				(code1, code2) = (code2, code1);
			}
			float m;
			if (x2 != x1)
				m = (float)(y2 - y1) / (x2 - x1);
			else
				m = 1.0f;
			if ((code1 & CLIP_LEFT_EDGE) != 0)
			{
				y1 = (short)(y1 + ToSint16((left - x1) * m));
				x1 = left;
			}
			else if ((code1 & CLIP_RIGHT_EDGE) != 0)
			{
				y1 = (short)(y1 + ToSint16((right - x1) * m));
				x1 = right;
			}
			else if ((code1 & CLIP_BOTTOM_EDGE) != 0)
			{
				if (x2 != x1)
					x1 = (short)(x1 + ToSint16((bottom - y1) / m));
				y1 = bottom;
			}
			else if ((code1 & CLIP_TOP_EDGE) != 0)
			{
				if (x2 != x1)
					x1 = (short)(x1 + ToSint16((top - y1) / m));
				y1 = top;
			}
		}
	}

	/// <summary>Draws a line (lineColor), clipped.</summary>
	public static void LineColor(Surface dst, short x1, short y1, short x2, short y2, byte color)
	{
		// Clip line and test if we have to draw
		if (!ClipLine(dst, ref x1, ref y1, ref x2, ref y2))
			return;

		// Test for special cases of straight lines or single point
		if (x1 == x2)
		{
			if (y1 < y2)
				VLineColor(dst, x1, y1, y2, color);
			else if (y1 > y2)
				VLineColor(dst, x1, y2, y1, color);
			else
				PixelColor(dst, x1, y1, color);
			return;
		}
		if (y1 == y2)
		{
			if (x1 < x2)
				HLineColor(dst, x1, x2, y1, color);
			else if (x1 > x2)
				HLineColor(dst, x2, x1, y1, color);
			return;
		}

		// Variable setup
		int dx = x2 - x1;
		int dy = y2 - y1;
		int sx = (dx >= 0) ? 1 : -1;
		int sy = (dy >= 0) ? 1 : -1;
		dx = sx * dx + 1;
		dy = sy * dy + 1;
		// Pixel steps: (pixx) along the longer axis, (pixy) along the other one.
		int pixxX = sx, pixxY = 0, pixyX = 0, pixyY = sy;
		if (dx < dy)
		{
			(dx, dy) = (dy, dx);
			(pixxX, pixxY, pixyX, pixyY) = (pixyX, pixyY, pixxX, pixxY);
		}

		// Draw
		int px = x1, py = y1;
		for (int x = 0, y = 0; x < dx; x++, px += pixxX, py += pixxY)
		{
			dst.FillLogical(px, py, 1, 1, color);
			y += dy;
			if (y >= dx)
			{
				y -= dx;
				px += pixyX;
				py += pixyY;
			}
		}
	}

	/// <summary>Draws a filled circle (filledCircleColor), clipped; negative radii draw nothing.</summary>
	public static void FilledCircleColor(Surface dst, short x, short y, short rad, byte color)
	{
		short cx = 0;
		short cy = rad;
		short ocx = unchecked((short)0xffff);
		short ocy = unchecked((short)0xffff);
		short df = (short)(1 - rad);
		short d_e = 3;
		short d_se = (short)(-2 * rad + 5);

		// Check visibility of clipping rectangle
		if (NoClip(dst))
			return;
		// Sanity check radius
		if (rad < 0)
			return;
		// Special case for rad=0 - draw a point
		if (rad == 0)
		{
			PixelColor(dst, x, y, color);
			return;
		}

		// Get circle and clipping boundary and test if bounding box of circle is visible
		short x2 = (short)(x + rad);
		short left = 0;
		if (x2 < left)
			return;
		short x1 = (short)(x - rad);
		short right = Right(dst);
		if (x1 > right)
			return;
		short y2 = (short)(y + rad);
		short top = 0;
		if (y2 < top)
			return;
		short y1 = (short)(y - rad);
		short bottom = Bottom(dst);
		if (y1 > bottom)
			return;

		// Draw
		do
		{
			short xpcx = (short)(x + cx);
			short xmcx = (short)(x - cx);
			short xpcy = (short)(x + cy);
			short xmcy = (short)(x - cy);
			if (ocy != cy)
			{
				if (cy > 0)
				{
					short ypcy = (short)(y + cy);
					short ymcy = (short)(y - cy);
					HLineColor(dst, xmcx, xpcx, ypcy, color);
					HLineColor(dst, xmcx, xpcx, ymcy, color);
				}
				else
				{
					HLineColor(dst, xmcx, xpcx, y, color);
				}
				ocy = cy;
			}
			if (ocx != cx)
			{
				if (cx != cy)
				{
					if (cx > 0)
					{
						short ypcx = (short)(y + cx);
						short ymcx = (short)(y - cx);
						HLineColor(dst, xmcy, xpcy, ymcx, color);
						HLineColor(dst, xmcy, xpcy, ypcx, color);
					}
					else
					{
						HLineColor(dst, xmcy, xpcy, y, color);
					}
				}
				ocx = cx;
			}
			// Update
			if (df < 0)
			{
				df = (short)(df + d_e);
				d_e = (short)(d_e + 2);
				d_se = (short)(d_se + 2);
			}
			else
			{
				df = (short)(df + d_se);
				d_e = (short)(d_e + 2);
				d_se = (short)(d_se + 4);
				cy--;
			}
			cx++;
		} while (cx <= cy);
	}

	/// <summary>
	/// Scanline intersections of a polygon with row <paramref name="y"/> in 16.16 fixed point, sorted
	/// (the inner loop of filledPolygonColorMT and texturedPolygonMT).
	/// </summary>
	private static int Intersections(ReadOnlySpan<short> vx, ReadOnlySpan<short> vy, int n, int y, int maxy, Span<int> polyInts)
	{
		int ints = 0;
		for (int i = 0; i < n; i++)
		{
			int ind1, ind2;
			if (i == 0)
			{
				ind1 = n - 1;
				ind2 = 0;
			}
			else
			{
				ind1 = i - 1;
				ind2 = i;
			}
			int y1 = vy[ind1];
			int y2 = vy[ind2];
			int x1, x2;
			if (y1 < y2)
			{
				x1 = vx[ind1];
				x2 = vx[ind2];
			}
			else if (y1 > y2)
			{
				y2 = vy[ind1];
				y1 = vy[ind2];
				x2 = vx[ind1];
				x1 = vx[ind2];
			}
			else
			{
				continue;
			}
			if ((y >= y1 && y < y2) || (y == maxy && y > y1 && y <= y2))
				polyInts[ints++] = ((65536 * (y - y1)) / (y2 - y1)) * (x2 - x1) + (65536 * x1);
		}
		polyInts[..ints].Sort();
		return ints;
	}

	/// <summary>Rounds a 16.16 fixed point span start (true) or end (false) to a pixel, like the C code.</summary>
	private static int SpanEnd(int fixedPoint, bool start)
	{
		int v = start ? fixedPoint + 1 : fixedPoint - 1;
		return (v >> 16) + ((v & 32768) >> 15);
	}

	/// <summary>Draws a filled polygon (filledPolygonColor); fewer than 3 points draw nothing.</summary>
	public static void FilledPolygonColor(Surface dst, ReadOnlySpan<short> vx, ReadOnlySpan<short> vy, int n, byte color)
	{
		// Check visibility of clipping rectangle
		if (NoClip(dst))
			return;
		// Sanity check number of edges
		if (n < 3)
			return;

		// Determine Y maxima
		int miny = vy[0];
		int maxy = vy[0];
		for (int i = 1; i < n; i++)
		{
			if (vy[i] < miny)
				miny = vy[i];
			else if (vy[i] > maxy)
				maxy = vy[i];
		}

		// Draw, scanning y
		Span<int> polyInts = n <= 256 ? stackalloc int[n] : new int[n];
		for (int y = miny; y <= maxy; y++)
		{
			int ints = Intersections(vx, vy, n, y, maxy, polyInts);
			for (int i = 0; i < ints; i += 2)
			{
				int xa = SpanEnd(polyInts[i], true);
				int xb = SpanEnd(polyInts[i + 1], false);
				HLineColor(dst, (short)xa, (short)xb, (short)y, color);
			}
		}
	}

	/// <summary>Internal function to draw a textured horizontal line (_HLineTextured), clipped; texture index 0 is transparent.</summary>
	private static void HLineTextured(Surface dst, short x1, short x2, short y, Surface texture, int texture_dx, int texture_dy)
	{
		// Check visibility of clipping rectangle
		if (NoClip(dst))
			return;
		// Swap x1, x2 if required to ensure x1<=x2
		if (x1 > x2)
			(x1, x2) = (x2, x1);
		// Get clipping boundary and check visibility of hline
		short left = 0;
		if (x2 < left)
			return;
		short right = Right(dst);
		if (x1 > right)
			return;
		short top = 0;
		short bottom = Bottom(dst);
		if (y < top || y > bottom)
			return;
		// Clip x
		if (x1 < left)
			x1 = left;
		if (x2 > right)
			x2 = right;

		// Calculate width to draw
		short w = (short)(x2 - x1 + 1);

		// Determine where in the texture we start drawing
		int texture_x_walker = (x1 - texture_dx) % texture.Width;
		if (texture_x_walker < 0)
			texture_x_walker = texture.Width + texture_x_walker;
		int texture_y_start = (y + texture_dy) % texture.Height;
		if (texture_y_start < 0)
			texture_y_start = texture.Height + texture_y_start;

		// if there are enough pixels left in the current row of the texture draw it all at once
		if (w <= texture.Width - texture_x_walker)
		{
			BlitTextureRow(texture, texture_x_walker, texture_y_start, w, dst, x1, y);
		}
		else
		{
			// we need to draw multiple times: the first segment, then the rest from source x 0
			int pixels_written = texture.Width - texture_x_walker;
			BlitTextureRow(texture, texture_x_walker, texture_y_start, pixels_written, dst, x1, y);
			int write_width = texture.Width;
			while (pixels_written < w)
			{
				if (write_width >= w - pixels_written)
					write_width = w - pixels_written;
				BlitTextureRow(texture, 0, texture_y_start, write_width, dst, (short)(x1 + pixels_written), y);
				pixels_written += write_width;
			}
		}
	}

	/// <summary>SDL_BlitSurface of a one row high part of the texture (colour key 0).</summary>
	private static void BlitTextureRow(Surface texture, int sx, int sy, int w, Surface dst, int dx, int dy)
	{
		texture.BlitRect(dst, dx - sx, dy - sy, sx, sy, sx + w, sy + 1, new Surface.KeyedCopyOp());
	}

	/// <summary>Draws a polygon filled with a texture (texturedPolygon); fewer than 3 points draw nothing.</summary>
	/// <param name="dst">The destination surface.</param>
	/// <param name="vx">X coordinates of the points.</param>
	/// <param name="vy">Y coordinates of the points.</param>
	/// <param name="n">Number of points.</param>
	/// <param name="texture">The surface to fill the polygon with (repeated).</param>
	/// <param name="texture_dx">X offset of the texture relative to the screen.</param>
	/// <param name="texture_dy">Y offset of the texture relative to the screen.</param>
	public static void TexturedPolygon(Surface dst, ReadOnlySpan<short> vx, ReadOnlySpan<short> vy, int n, Surface texture, int texture_dx, int texture_dy)
	{
		// Check visibility of clipping rectangle
		if (NoClip(dst))
			return;
		// Sanity check number of edges
		if (n < 3)
			return;

		// Determine X,Y minima,maxima
		int miny = vy[0];
		int maxy = vy[0];
		int minx = vx[0];
		int maxx = vx[0];
		for (int i = 1; i < n; i++)
		{
			if (vy[i] < miny)
				miny = vy[i];
			else if (vy[i] > maxy)
				maxy = vy[i];
			if (vx[i] < minx)
				minx = vx[i];
			else if (vx[i] > maxx)
				maxx = vx[i];
		}
		if (maxx < 0 || minx > dst.Width)
			return;
		if (maxy < 0 || miny > dst.Height)
			return;

		// Draw, scanning y
		Span<int> polyInts = n <= 256 ? stackalloc int[n] : new int[n];
		for (int y = miny; y <= maxy; y++)
		{
			int ints = Intersections(vx, vy, n, y, maxy, polyInts);
			for (int i = 0; i < ints; i += 2)
			{
				int xa = SpanEnd(polyInts[i], true);
				int xb = SpanEnd(polyInts[i + 1], false);
				HLineTextured(dst, (short)xa, (short)xb, (short)y, texture, texture_dx, texture_dy);
			}
		}
	}

	/// <summary>The 8 rows of a character of the built-in font (bit 7 = left pixel), for drawing on true colour images.</summary>
	public static ReadOnlySpan<byte> Glyph(byte c) => FontData.Slice(c * CharSize, CharSize);

	/// <summary>Draws a character of the built-in 8x8 font (characterColor), clipped.</summary>
	public static void CharacterColor(Surface dst, short x, short y, byte c, byte color)
	{
		// Check visibility of clipping rectangle
		if (NoClip(dst))
			return;
		// Get text and clipping boundary and test if bounding box of character is visible
		short left = 0;
		short x2 = (short)(x + CharSize);
		if (x2 < left)
			return;
		short right = Right(dst);
		short x1 = x;
		if (x1 > right)
			return;
		short top = 0;
		short y2 = (short)(y + CharSize);
		if (y2 < top)
			return;
		short bottom = Bottom(dst);
		short y1 = y;
		if (y1 > bottom)
			return;

		// The font surface is RGBA with alpha 0 for the background: only set bits are blit.
		var charpos = FontData.Slice(c * CharSize, CharSize);
		for (int iy = 0; iy < CharSize; iy++)
		{
			byte patt = charpos[iy];
			for (int ix = 0; ix < CharSize; ix++)
			{
				if ((patt & (0x80 >> ix)) != 0 && x + ix >= 0 && x + ix < dst.Width && y + iy >= 0 && y + iy < dst.Height)
					dst.FillLogical(x + ix, y + iy, 1, 1, color);
			}
		}
	}

	/// <summary>Draws a zero-terminated string of the built-in font (stringColor), 8 pixels per character.</summary>
	public static void StringColor(Surface dst, short x, short y, ReadOnlySpan<byte> s, byte color)
	{
		short curx = x;
		short cury = y;
		foreach (byte c in s)
		{
			if (c == 0)
				break;
			CharacterColor(dst, curx, cury, c, color);
			curx = (short)(curx + CharSize);
		}
	}
