namespace Acom.Tests.Engine;

public class GMCatTests
{
	private static void Seq(List<byte> d, params byte[] body)
	{
		d.AddRange(BitConverter.GetBytes(body.Length + 4));
		d.AddRange(body);
	}

	/// <summary>A gm.cat item: name chunk, tempo, one subsequence, two tracks (channel 2 and percussion).</summary>
	private static byte[] Item()
	{
		var d = new List<byte> { 3, (byte)'a', (byte)'b', (byte)'c', 120, 1 };
		Seq(d, 0x00, 0x90, 0x40, 0x64, 0x05, 0x80, 0x40, 0x00, 0x00, 0xFD);
		d.Add(2);
		d.Add(2);
		Seq(d, 0x00, 0xC0, 0x05, 0x00, 0xB0, 0x00, 0x32, 0x00, 0xB0, 0x5B, 0x40, 0x00, 0xFE, 0x00, 0x03, 0xE0, 0x00, 0x40,
			0x02, 0xC0, 0x57, 0x01, 0xB0, 0x7E, 0x01, 0x81, 0x00, 0x90, 0x3C, 0x50, 0x00, 0x3E, 0x50, 0x00, 0xB0, 0x00, 0x00,
			0x04, 0xC0, 0x7E);
		d.Add(9);
		Seq(d, 0x00, 0x99, 0x24, 0x7F, 0x10, 0x89, 0x24, 0x00, 0x00, 0xFF);
		return [.. d];
	}

	/// <summary>Output of the C++ gmext_read_stream/gmext_write_midi for <see cref="Item"/>.</summary>
	private static readonly byte[] s_expectedMidi =
	[
		0x4D, 0x54, 0x68, 0x64, 0x00, 0x00, 0x00, 0x06, 0x00, 0x01, 0x00, 0x03, 0x00, 0x18, 0x4D, 0x54, 0x72, 0x6B, 0x00, 0x00,
		0x00, 0x0B, 0x00, 0xFF, 0x51, 0x03, 0x07, 0xA1, 0x20, 0x00, 0xFF, 0x2F, 0x00, 0x4D, 0x54, 0x72, 0x6B, 0x00, 0x00, 0x00,
		0x34, 0x00, 0xB2, 0x78, 0x00, 0x00, 0x79, 0x00, 0x00, 0x7B, 0x00, 0x00, 0xC2, 0x05, 0x00, 0xFF, 0x51, 0x03, 0x09, 0x27,
		0xC0, 0x00, 0xB2, 0x5B, 0x1E, 0x00, 0x92, 0x40, 0x46, 0x05, 0x82, 0x40, 0x00, 0x03, 0xE2, 0x00, 0x40, 0x02, 0xC2, 0x3E,
		0x81, 0x01, 0x92, 0x3C, 0x47, 0x00, 0x92, 0x3E, 0x47, 0x04, 0xFF, 0x2F, 0x00, 0x4D, 0x54, 0x72, 0x6B, 0x00, 0x00, 0x00,
		0x16, 0x00, 0xB9, 0x78, 0x00, 0x00, 0x79, 0x00, 0x00, 0x7B, 0x00, 0x00, 0x99, 0x24, 0x4F, 0x10, 0x89, 0x24, 0x00, 0x00,
		0xFF, 0x2F, 0x00,
	];

	[Fact]
	public void Stream_converts_to_the_same_midi_file_as_the_original()
	{
		Assert.Equal(0, GMCatFile.ConvertToMidi(Item(), out byte[] midi));
		Assert.Equal(s_expectedMidi, midi);
	}

	[Fact]
	public void Broken_streams_are_rejected()
	{
		// a track longer than the data (C++: the unsigned length wraps around, then the rest check fails)
		Assert.Equal(-1, GMCatFile.ConvertToMidi([0, 120, 0, 1, 0, 50, 0, 0, 0, 0x00], out _));
		Assert.Equal(-1, GMCatFile.ConvertToMidi([5, 1, 2], out _)); // shorter than its name
		byte[] item = Item();
		item[^1] = 0x70; // running status without a command
		Assert.Equal(-2, GMCatFile.ConvertToMidi(item, out _));
	}

	[Fact]
	public void LoadMIDI_returns_an_empty_track_for_a_broken_stream()
	{
		var cat = new List<byte>();
		cat.AddRange(BitConverter.GetBytes(8));
		cat.AddRange(BitConverter.GetBytes(3));
		cat.AddRange([5, 1, 2]);
		var file = new GMCatFile(new MemoryStream([.. cat]), "GM.CAT");
		Assert.NotNull(file.LoadMIDI(0));
		Assert.Throws<InvalidOperationException>(() => file.LoadMIDI(1));
	}
}
