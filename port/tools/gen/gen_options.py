#!/usr/bin/env python3
"""Generates the C# option declarations and registrations from the C++ sources.

Inputs:  src/Engine/Options.inc.h, src/Engine/Options.h (enums), src/Engine/Options.cpp (create* functions)
Outputs: port/src/Acom.Core/Engine/Options.Values.cs, port/src/Acom.Core/Engine/Options.Create.cs

The C preprocessor resolves platform branches with desktop defines (no __MOBILE__, no DINGOO).
Run from anywhere: python3 port/tools/gen/gen_options.py
"""
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "src" / "Engine"
OUT = ROOT / "port" / "src" / "Acom.Core" / "Engine"
HEADER = (ROOT / "port" / "tools" / "license-header.txt").read_text()

# --- enums from Options.h plus types declared elsewhere -------------------------------------
enum_values = {}   # value name -> enum type
enum_types = set()
for m in re.finditer(r"enum\s+(\w+)\s*\{([^}]*)\}", (SRC / "Options.h").read_text()):
    enum_types.add(m.group(1))
    for v in re.findall(r"\b([A-Z][A-Z0-9_]+)\b\s*(?:=|,|$|\n)", m.group(2)):
        enum_values[v] = m.group(1)
for t, values in {"TextWrapping": ["WRAP_AUTO", "WRAP_WORDS", "WRAP_LETTERS"],
                  "SDL_GrabMode": ["SDL_GRAB_QUERY", "SDL_GRAB_OFF", "SDL_GRAB_ON"],
                  "SeverityLevel": ["LOG_FATAL", "LOG_ERROR", "LOG_WARNING", "LOG_INFO", "LOG_DEBUG", "LOG_VERBOSE", "LOG_UNCENSORED"]}.items():
    enum_types.add(t)
    for v in values:
        enum_values[v] = t

# --- declarations -----------------------------------------------------------------------------
inc = (SRC / "Options.inc.h").read_text()
inc = re.sub(r"/\*.*?\*/", "", inc, flags=re.S)
var_types = {}
decls = []  # (comment, type, names)
pending_comment = []
for stmt in re.finditer(r"(//[^\n]*)|OPT\s+(.+?);", inc, flags=re.S):
    if stmt.group(1):
        text = stmt.group(1)[2:].strip()
        if not text.startswith("Don't worry") and not text.startswith("To add a new option"):
            pending_comment.append(text)
        continue
    body = " ".join(stmt.group(2).split())
    m = re.match(r"(std::vector<\s*std::pair<std::string,\s*bool>\s*>|std::string|\w+)\s+(.*)", body)
    ctype, names = m.group(1), [n.strip() for n in m.group(2).split(",")]
    decls.append((pending_comment, ctype, names))
    pending_comment = []
    for n in names:
        var_types[n] = ctype

def cs_type(ctype):
    return {"int": "int", "bool": "bool", "std::string": "string", "SDLKey": "SDLKey"}.get(ctype, ctype)

lines = [HEADER.rstrip("\n"),
         "// Ported from: src/Engine/Options.inc.h, src/Engine/Options.h (enums)",
         "// GENERATED by port/tools/gen/gen_options.py - do not edit by hand.",
         "",
         "#pragma warning disable CA2211 // Global option variables, as in the C++ code.",
         "",
         "namespace Acom;",
         ""]
for m in re.finditer(r"enum\s+(\w+)\s*\{([^}]*)\}", (SRC / "Options.h").read_text()):
    body = re.sub(r"//[^\n]*", "", m.group(2))
    members = [x.strip() for x in body.split(",") if x.strip()]
    lines.append(f"public enum {m.group(1)}")
    lines.append("{")
    for member in members:
        lines.append(f"\t{' '.join(member.split())},")
    lines.append("}")
    lines.append("")
lines += ["/// <summary>Grab mode of the mouse (SDL 1.2 SDL_GrabMode).</summary>",
          "public enum SDL_GrabMode", "{", "\tSDL_GRAB_QUERY = -1,", "\tSDL_GRAB_OFF = 0,", "\tSDL_GRAB_ON = 1,", "}", "",
          "/// <summary>Global game options; field names are the keys in options.cfg.</summary>",
          "public static partial class Options",
          "{"]
for comment, ctype, names in decls:
    for c in comment:
        lines.append(f"\t// {c}")
    if ctype.startswith("std::vector"):
        lines.append("\t/// <summary>Ordered list of available mods (lowest priority to highest) and whether they are active.</summary>")
        lines.append("\tpublic static List<ModToggle> mods = [];")
        continue
    t = cs_type(ctype)
    init = ' = ""' if t == "string" else ""
    lines.append(f"\tpublic static {t} " + ", ".join(n + init for n in names) + ";")
lines.append("}")
(OUT / "Options.Values.cs").write_text("\n".join(lines) + "\n")

# --- registrations ------------------------------------------------------------------------------
cpp = (SRC / "Options.cpp").read_text().splitlines()
start = next(i for i, l in enumerate(cpp) if l.startswith("void create()"))
end = next(i for i, l in enumerate(cpp) if l.startswith("static bool _gameIsInstalled"))
snippet = "\n".join(l for l in cpp[start:end] if "#include" not in l)
pre = subprocess.run(["cpp", "-P", "-undef", "-nostdinc", "-D__linux__=1", "-C"], input=snippet, capture_output=True, text=True, check=True).stdout

def default_expr(expr, kind):
    expr = expr.strip()
    expr = re.sub(r"\bScreen::", "Screen.", expr)
    expr = re.sub(r"\b(SDLK_\w+)", r"SDLKey.\1", expr)
    expr = re.sub(r"\b(SDL_BUTTON_\w+)", r"SDLMouse.\1", expr)
    expr = re.sub(r"\(int\)\s*", "", expr) if kind == "int" else expr
    def enum_repl(m):
        v = m.group(1)
        if v in enum_values:
            e = f"{enum_values[v]}.{v}"
            return f"(int){e}" if kind == "int" else e
        return v
    return re.sub(r"(?<![.\w])([A-Z][A-Z0-9_]{2,})\b", enum_repl, expr)

out = [HEADER.rstrip("\n"),
       "// Ported from: src/Engine/Options.cpp (create, create*OXC, create*OXCE, create*OTHER)",
       "// GENERATED by port/tools/gen/gen_options.py - do not edit by hand.",
       "",
       "namespace Acom;",
       "",
       "public static partial class Options",
       "{"]
push = re.compile(r'_info\.push_back\(OptionInfo\((OPTION_\w+),\s*"(\w+)",\s*(\((\w+)\*\))?&(\w+),\s*(.*?)(?:,\s*("[^"]*"),\s*("[^"]*"))?\)\);(.*)$')
count = 0
for raw in pre.splitlines():
    line = raw.rstrip()
    if not line.strip():
        continue
    fm = re.match(r"void (create\w*)\(\)", line)
    if fm:
        name = fm.group(1)
        out.append("")
        out.append(f"\tpublic static void {name[0].upper() + name[1:]}()" if name != "create" else "\tpublic static void Create()")
        continue
    if line.strip() in ("{", "}"):
        out.append("\t" + line.strip())
        continue
    m = push.match(line.strip())
    if m:
        owner, oid, _, cast, var, default, desc, cat, tail = m.groups()
        ctype = var_types[var]
        if cast == "int" and ctype in enum_types:
            getter, setter, kind = f"() => (int){var}", f"v => {var} = ({ctype})v", "int"
        elif cast == "bool" and ctype in enum_types:
            getter, setter, kind = f"() => {var} != SDL_GrabMode.SDL_GRAB_OFF", f"v => {var} = v ? SDL_GrabMode.SDL_GRAB_ON : SDL_GrabMode.SDL_GRAB_OFF", "bool"
        else:
            getter, setter = f"() => {var}", f"v => {var} = v"
            kind = {"int": "int", "bool": "bool", "std::string": "string", "SDLKey": "key"}[ctype]
        args = [f"OptionOwner.{owner}", f'"{oid}"', getter, setter, default_expr(default, kind)]
        if desc:
            args += [desc, cat]
        out.append(f"\t\t_info.Add(new OptionInfo({', '.join(args)}));{tail}")
        count += 1
        continue
    s = line.strip()
    if s.startswith("if (!_info.empty())"):
        out.append("\t\t_info.Clear();")
        continue
    if re.match(r"\w+\(\);", s):
        out.append("\t\t" + s[0].upper() + s[1:])
        continue
    if s.startswith("//") or re.match(r"\w+ = -?\d+;", s):
        out.append("\t\t" + s)
        continue
    raise SystemExit(f"untranslated line: {s}")
out.append("}")
(OUT / "Options.Create.cs").write_text("\n".join(out) + "\n")
print(f"{len(var_types)} variables, {count} OptionInfo registrations")
